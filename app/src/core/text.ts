// Farbige Textbausteine für Aufgaben und Lösungen (gleiche Farben wie in den Bildern).
export const f = (t: string) => `<span class="cF">${t}</span>`; // Kraft
export const r = (t: string) => `<span class="cR">${t}</span>`; // Resultierende
export const l = (t: string) => `<span class="cL">${t}</span>`; // Länge
export const m = (t: string) => `<span class="cM">${t}</span>`; // Moment
export const v = (t: string) => `<span class="cV">${t}</span>`; // Energie, Geschwindigkeit
export const eq = (t: string) => `<span class="eq">${t}</span>`; // Formelzeile
